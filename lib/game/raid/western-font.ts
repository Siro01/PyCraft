/** Acentos (se centran sobre la letra, en las filas extra de arriba). */
const ACUTE = ['...##', '..##.', '.....']
const TILDE = ['.##.#', '#.##.', '.....']

const ACCENTED: Record<string, [string, string[]]> = {
  Á: ['A', ACUTE], É: ['E', ACUTE], Í: ['I', ACUTE], Ó: ['O', ACUTE], Ú: ['U', ACUTE], Ñ: ['N', TILDE], Ü: ['U', ['.#.#.', '.....', '.....']],
}

export interface WesternGlyph { rows: string[]; accent?: string[] }

export function glyphFor(ch: string): WesternGlyph {
  const up = ch.toLocaleUpperCase('es')
  if (G[up]) return { rows: G[up] }
  const acc = ACCENTED[up]
  if (acc) return { rows: G[acc[0]], accent: acc[1] }
  return { rows: G[' '] }
}

/**
 * Texto → mapa de píxeles (filas de '#' y '.'), con 1 columna de separación
 * entre letras. Alto = ACCENT_H + GLYPH_H.
 */
export function layoutWestern(text: string): string[] {
  const H = ACCENT_H + GLYPH_H
  const rows = Array.from({ length: H }, () => '')
  ;[...text].forEach((ch, i) => {
    const g = glyphFor(ch)
    const w = g.rows[0].length
    for (let y = 0; y < H; y++) {
      let line: string
      if (y < ACCENT_H) {
        const a = g.accent?.[y] ?? ''
        const pad = Math.max(0, Math.floor((w - a.length) / 2))
        line = ('.'.repeat(pad) + a).padEnd(w, '.').slice(0, w)
      } else line = g.rows[y - ACCENT_H]
      rows[y] += (i > 0 ? '.' : '') + line
    }
  })
  return rows
}
